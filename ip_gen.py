houses = []
for i in range(m):
    start_day = random.randint(1, n)
    end_day = random.randint(start_day, n)
    houses.append((start_day, end_day))

print(n, m)
for house in houses:
    print(house[0], house[1], end=' ',file=outFile)
    print(file=outFile)
outFile.close()

